"""Clinical reasoning endpoints (M5).

The parent-facing summary is behind an explicit flag AND a permission, default
off. It is the highest-risk output in the product: a plain-language line read by
a worried parent carries far more weight than the same line read by a clinician,
and it must not leave the building without a clinician choosing to release it.
"""
from __future__ import annotations

from typing import Any

from fastapi import APIRouter, Depends, HTTPException, Query
from sqlalchemy.orm import Session

from backend import clinical_service as svc
from backend import growth_service
from backend.clinical import prediction, referral, rules
from backend.db import get_db
from backend.models import User
from backend.security import roles
from backend.security.deps import clinical_access, require

router = APIRouter(
    prefix="/api/clinical",
    tags=["clinical"],
    dependencies=[Depends(clinical_access)],
)


@router.get("/rules")
def list_rules() -> dict[str, Any]:
    """Every rule, its required inputs and its threshold source.

    Published deliberately: a clinician who cannot see what the engine checks and
    on whose authority has no reason to trust it.
    """
    return {
        "rules": [
            {"rule_id": r.rule_id, "describes": r.describe, "requires": list(r.requires)}
            for r in rules.registry()
        ],
        "thresholds": {
            k: v for k, v in rules.thresholds().items() if not k.startswith("_")
        },
        "triage_levels": list(referral.TRIAGE_LEVELS),
        "note": "No triage level tells a patient they are fine. Anthropometry can "
                "indicate that something needs review; it cannot exclude disease.",
    }


@router.get("/patients/{patient_id}/assessment")
def assessment(patient_id: int, db: Session = Depends(get_db)) -> dict[str, Any]:
    """Findings, triage and adult-height context for one patient."""
    try:
        return svc.assess(db, patient_id)
    except growth_service.GrowthRecordError as exc:
        raise HTTPException(404, str(exc)) from exc


@router.get("/patients/{patient_id}/parent-summary")
def parent_summary(patient_id: int,
                   release: bool = Query(False,
                                         description="must be explicitly true; "
                                                     "clinician-released output"),
                   db: Session = Depends(get_db),
                   _: User = Depends(require(roles.APPROVE_CLINICAL))) -> dict[str, Any]:
    """Plain-language summary for a parent. Clinician-released only.

    Requires APPROVE_CLINICAL (a doctor) AND an explicit release flag. Two gates
    rather than one because the failure mode is not a wrong number, it is a
    worried parent acting on a sentence nobody chose to send them.
    """
    if not release:
        raise HTTPException(
            403,
            "parent-facing output must be explicitly released by a clinician "
            "(pass release=true). It is not generated by default.",
        )
    try:
        return svc.assess(db, patient_id, include_parent_summary=True)["parent_summary"]
    except growth_service.GrowthRecordError as exc:
        raise HTTPException(404, str(exc)) from exc


@router.get("/patients/{patient_id}/adult-height")
def adult_height(patient_id: int, db: Session = Depends(get_db)) -> dict[str, Any]:
    """Genetic target and predicted adult height, separately labelled (audit F-1)."""
    try:
        s = svc.build_snapshot(db, patient_id)
    except growth_service.GrowthRecordError as exc:
        raise HTTPException(404, str(exc)) from exc
    return prediction.adult_height_summary(
        s.sex, s.age_years,
        s.height.value if s.height else None,
        s.weight.value if s.weight else None,
        s.mother_height_cm, s.father_height_cm, s.parental_height_source,
        bone_age_years=s.bone_age_years,
    )
